/** Conserva un fallback en español si se agrega una clave nueva a un solo idioma. */
export function t(locale: Locale, key: string, variables: Record<string, string | number> = {}): string {
  const template = dictionaries[locale][key] ?? dictionaries.es[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}
